  CommonArea,
  'createdAt' | 'updatedAt' | 'deletedAt'
>[] = (() => {
  let id = 1
  return Object.keys(areasByBuilding)
    .map(Number)
    .sort((a, b) => a - b)
    .flatMap(buildingId =>
      areasByBuilding[buildingId].map(area => ({
        id: id++,
        buildingId,
        isActive: true,
        ...area,
      }))
    )
})()

